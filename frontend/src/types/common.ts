/**
 * -----------------------------------------------------------------------------
 * Common Types
 * -----------------------------------------------------------------------------
 *
 * Shared types used throughout the application.
 *
 * -----------------------------------------------------------------------------
 */

/* -------------------------------------------------------------------------- */
/* Nullable                                                                   */
/* -------------------------------------------------------------------------- */

export type Nullable<T> = T | null;

/* -------------------------------------------------------------------------- */
/* Optional                                                                   */
/* -------------------------------------------------------------------------- */

export type Optional<T> = T | undefined;

/* -------------------------------------------------------------------------- */
/* Value Of                                                                   */
/* -------------------------------------------------------------------------- */

export type ValueOf<T> = T[ keyof T ];

/* -------------------------------------------------------------------------- */
/* Dictionary                                                                 */
/* -------------------------------------------------------------------------- */

export type Dictionary<T = unknown> = Record<string, T>;

/* -------------------------------------------------------------------------- */
/* Primitive                                                                  */
/* -------------------------------------------------------------------------- */

export type Primitive =
    | string
    | number
    | boolean
    | bigint
    | symbol
    | null
    | undefined;

/* -------------------------------------------------------------------------- */
/* ID                                                                         */
/* -------------------------------------------------------------------------- */

export type ID = string;

/* -------------------------------------------------------------------------- */
/* ISO Date                                                                   */
/* -------------------------------------------------------------------------- */

export type ISODateString = string;

/* -------------------------------------------------------------------------- */
/* Size                                                                       */
/* -------------------------------------------------------------------------- */

export type Size =
    | "xs"
    | "sm"
    | "md"
    | "lg"
    | "xl";

/* -------------------------------------------------------------------------- */
/* Variant                                                                    */
/* -------------------------------------------------------------------------- */

export type Variant =
    | "default"
    | "primary"
    | "secondary"
    | "outline"
    | "ghost"
    | "destructive"
    | "success"
    | "warning";

/* -------------------------------------------------------------------------- */
/* Status                                                                     */
/* -------------------------------------------------------------------------- */

export type Status =
    | "idle"
    | "loading"
    | "success"
    | "error";

/* -------------------------------------------------------------------------- */
/* Direction                                                                  */
/* -------------------------------------------------------------------------- */

export type Direction =
    | "horizontal"
    | "vertical";

/* -------------------------------------------------------------------------- */
/* Theme                                                                      */
/* -------------------------------------------------------------------------- */

export type Theme =
    | "light"
    | "dark"
    | "system";